const CACHE = 'wc2026-v3';
const ASSETS = ['./', './index.html', './manifest.json', './icon.svg'];

self.addEventListener('install', e => {
  e.waitUntil(caches.open(CACHE).then(c => c.addAll(ASSETS)));
  self.skipWaiting();
});

self.addEventListener('activate', e => {
  e.waitUntil(
    caches.keys().then(keys =>
      Promise.all(keys.filter(k => k !== CACHE).map(k => caches.delete(k)))
    ).then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', e => {
  const url = new URL(e.request.url);
  // la API de ESPN siempre va a la red; el resto, cache-first con actualización
  if (url.origin !== location.origin) return;
  // HTML: red primero (cambios visibles al instante), caché solo como respaldo offline
  const networkFirst = e.request.mode === 'navigate' || url.pathname.endsWith('.html');
  e.respondWith(
    caches.match(e.request).then(cached => {
      const fresh = fetch(e.request).then(res => {
        if (res.ok) {
          const clone = res.clone();
          caches.open(CACHE).then(c => c.put(e.request, clone));
        }
        return res;
      }).catch(() => cached);
      return networkFirst ? fresh : (cached || fresh);
    })
  );
});
